"""Object store adapter interface and shared helpers (FD-OBJ).

All three adapters (memory, local filesystem, S3) implement the same
:class:`ObjectStore` contract.  Content is always handled as a *stream*: writes
and reads are chunked so a 100 MB artifact never has to be buffered in memory
(FD-ART-006, FD-NFR-04).

Object paths are generated by S0 (FD-OBJ-002) as ``<project>/<type>/<artifactId>``;
callers never hand-craft keys and subsystems never touch the store directly.
"""

from __future__ import annotations

import hashlib
from collections.abc import Iterable, Iterator
from dataclasses import dataclass
from pathlib import PurePosixPath
from typing import Protocol, runtime_checkable

# 1 MiB chunks: small enough to bound memory, large enough for throughput.
CHUNK_SIZE = 1 << 20


@runtime_checkable
class ObjectStore(Protocol):
    def put(
        self, key: str, source: object, *, media_type: str = "application/octet-stream"
    ) -> PutResult: ...

    def open_read(self, key: str) -> ReadHandle: ...

    def delete(self, key: str) -> None: ...

    def exists(self, key: str) -> bool: ...


@dataclass(frozen=True)
class PutResult:
    key: str
    location: str
    size: int
    sha256_hex: str  # digest computed incrementally during the write


@dataclass(frozen=True)
class ReadHandle:
    """A closed-over-streaming reader: hash the content while consuming it."""

    key: str
    chunks: Iterator[bytes]
    size: int | None

    def iter_bytes(self) -> Iterator[bytes]:
        yield from self.chunks

    def read_all(self) -> bytes:
        return b"".join(self.chunks)

    def sha256_hex(self) -> str:
        h = hashlib.sha256()
        for chunk in self.chunks:
            h.update(chunk)
        return h.hexdigest()


def normalize_source(source: object) -> Iterator[bytes]:
    """Turn a file-like object, an iterable of bytes, or ``bytes`` into a chunk iterator."""
    if isinstance(source, bytes):
        for i in range(0, len(source), CHUNK_SIZE):
            yield source[i : i + CHUNK_SIZE]
        return
    if hasattr(source, "read"):  # file-like
        while True:
            chunk = source.read(CHUNK_SIZE)
            if not chunk:
                break
            yield chunk
        return
    if isinstance(source, Iterable):
        for chunk in source:
            if chunk:
                yield chunk
        return
    raise TypeError(f"unsupported source type: {type(source).__name__}")


def build_object_path(project_id: str, artifact_type: str, artifact_id: str) -> str:
    """S0-owned object path (FD-OBJ-002): project / type / id."""
    return f"{project_id}/{artifact_type}/{artifact_id}"


def key_from_location(location: str, store: object) -> str:
    """Recover the key that ``store`` wrote ``location`` for (FD-OBJ-001 round-trip).

    An artifact row persists only ``content_location``, so reading, purging and
    retention must map the location back to a key.  The tail is store-relative:
    the local store roots keys at its directory and an S3 store prefixes them, so
    plain scheme-stripping would hand back a path the store rejects or mis-prefixed.
    """
    if location.startswith("memory://"):
        return location[len("memory://") :]
    if location.startswith("file://"):
        path = location[len("file://") :]
        root = getattr(store, "root", None)
        if root is None:
            return path
        try:
            return str(PurePosixPath(path).relative_to(PurePosixPath(str(root))))
        except ValueError:
            return path
    if location.startswith("s3://"):
        _bucket, _, tail = location[len("s3://") :].partition("/")
        prefix = str(getattr(store, "prefix", "") or "")
        if prefix and tail.startswith(f"{prefix}/"):
            tail = tail[len(prefix) + 1 :]
        return tail
    return location
